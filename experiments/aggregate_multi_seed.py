"""Aggregate multi-seed CSVs into per-(dataset, provider) mean ± std metrics.

Outputs:
  - experiments/results/multi_seed_summary.csv         (one row per dataset, providers as columns)
  - experiments/results/multi_seed_summary.md          (markdown table for human review)
  - experiments/results/multi_seed_summary.tex         (LaTeX table for the paper)

    python experiments/aggregate_multi_seed.py
"""

from __future__ import annotations

import sys
from pathlib import Path

import numpy as np
import pandas as pd

REPO = Path(__file__).resolve().parent.parent


DATASET_DISPLAY = {
    "cic":   "CIC-IoT2023",
    "wustl": "WUSTL-IIoT",
    "ton":   "TON\\_IoT",
    "bot":   "Bot-IoT",
    "unsw":  "UNSW-NB15",
}
DATASET_ORDER = ["cic", "wustl", "ton", "bot", "unsw"]


def fmt(mean: float, std: float, places: int = 4) -> str:
    return f"{mean:.{places}f} $\\pm$ {std:.{places}f}"


def fmt_md(mean: float, std: float, places: int = 4) -> str:
    return f"{mean:.{places}f} ± {std:.{places}f}"


def main():
    sweeps = sorted((REPO / "experiments" / "sweeps").glob("multi_seed-*.csv"))
    if not sweeps:
        print("No multi_seed CSVs found")
        return
    df = pd.concat([pd.read_csv(p) for p in sweeps], ignore_index=True)
    print(f"Loaded {len(df)} rows from {len(sweeps)} multi_seed CSV(s)")

    if "error" in df.columns:
        df = df[df["error"].isna()]
    print(f"After dropping errors: {len(df)} rows")

    metric_cols = ["macro_f1", "attack_f1", "attack_precision", "attack_recall",
                   "normal_f1", "n_distinct_tags"]
    grouped = (df.groupby(["dataset", "provider"])[metric_cols]
                 .agg(["mean", "std"]))
    print("\n=== AGGREGATED (mean, std per dataset × provider) ===\n")
    print(grouped.to_string(float_format=lambda x: f"{x:.4f}"))

    out_dir = REPO / "experiments" / "results"
    out_dir.mkdir(exist_ok=True)
    grouped.to_csv(out_dir / "multi_seed_summary.csv", float_format="%.4f")

    # ── Markdown table ──
    md = ["# Multi-Seed Policy Pipeline Results (3 seeds: 42, 123, 456)\n\n"]
    md.append("Mean ± std on the held-out test split, per dataset × LLM vendor.\n\n")
    md.append("## Macro F1\n\n")
    md.append("| Dataset | Claude Haiku 4.5 | Gemini 2.5 Flash |\n|---|---|---|\n")
    for ds in DATASET_ORDER:
        try:
            h = grouped.loc[(ds, "anthropic")]
            g = grouped.loc[(ds, "google")]
        except KeyError:
            continue
        md.append(f"| {DATASET_DISPLAY[ds].replace(chr(92)*2, '')} | "
                  f"{fmt_md(h['macro_f1', 'mean'], h['macro_f1', 'std'])} | "
                  f"{fmt_md(g['macro_f1', 'mean'], g['macro_f1', 'std'])} |\n")
    md.append("\n## Attack-Class F1\n\n")
    md.append("| Dataset | Haiku | Gemini |\n|---|---|---|\n")
    for ds in DATASET_ORDER:
        try:
            h = grouped.loc[(ds, "anthropic")]
            g = grouped.loc[(ds, "google")]
        except KeyError:
            continue
        md.append(f"| {DATASET_DISPLAY[ds].replace(chr(92)*2, '')} | "
                  f"{fmt_md(h['attack_f1', 'mean'], h['attack_f1', 'std'])} | "
                  f"{fmt_md(g['attack_f1', 'mean'], g['attack_f1', 'std'])} |\n")
    md.append("\n## Attack-Class Precision / Recall (Haiku)\n\n")
    md.append("| Dataset | Precision | Recall |\n|---|---|---|\n")
    for ds in DATASET_ORDER:
        try:
            h = grouped.loc[(ds, "anthropic")]
        except KeyError:
            continue
        md.append(f"| {DATASET_DISPLAY[ds].replace(chr(92)*2, '')} | "
                  f"{fmt_md(h['attack_precision', 'mean'], h['attack_precision', 'std'])} | "
                  f"{fmt_md(h['attack_recall', 'mean'], h['attack_recall', 'std'])} |\n")
    md.append("\n## Attack-Class Precision / Recall (Gemini)\n\n")
    md.append("| Dataset | Precision | Recall |\n|---|---|---|\n")
    for ds in DATASET_ORDER:
        try:
            g = grouped.loc[(ds, "google")]
        except KeyError:
            continue
        md.append(f"| {DATASET_DISPLAY[ds].replace(chr(92)*2, '')} | "
                  f"{fmt_md(g['attack_precision', 'mean'], g['attack_precision', 'std'])} | "
                  f"{fmt_md(g['attack_recall', 'mean'], g['attack_recall', 'std'])} |\n")
    (out_dir / "multi_seed_summary.md").write_text("".join(md))

    # ── LaTeX table: tab:policy_refinement replacement ──
    tex = ["% Generated by experiments/aggregate_multi_seed.py — paste into results.tex\n"]
    tex.append("\\begin{table}[H]\n\\centering\n")
    tex.append("\\caption{Held-out test macro-averaged F1 with cross-vendor agreement.\n")
    tex.append("  Mean $\\pm$ std over three seeds $\\{42, 123, 456\\}$.\n")
    tex.append("  Best-round selected on a stratified validation slice; the test split is touched once.}\n")
    tex.append("\\label{tab:policy_refinement}\n")
    tex.append("\\begin{tabular}{lcc}\n\\toprule\n")
    tex.append("\\textbf{Dataset} & \\textbf{Claude Haiku 4.5} & \\textbf{Gemini 2.5 Flash} \\\\\n\\midrule\n")
    for ds in DATASET_ORDER:
        try:
            h = grouped.loc[(ds, "anthropic")]; g = grouped.loc[(ds, "google")]
        except KeyError:
            continue
        tex.append(f"{DATASET_DISPLAY[ds]} & {fmt(h['macro_f1', 'mean'], h['macro_f1', 'std'])} & "
                   f"{fmt(g['macro_f1', 'mean'], g['macro_f1', 'std'])} \\\\\n")
    tex.append("\\bottomrule\n\\end{tabular}\n\\end{table}\n\n")

    # ── LaTeX table: tab:attack_precision_current replacement ──
    tex.append("\\begin{table}[htbp]\n\\centering\n")
    tex.append("\\caption{Attack-class precision / recall / F1 on the held-out test split.\n")
    tex.append("  Mean $\\pm$ std over three seeds. Haiku columns first, then Gemini.}\n")
    tex.append("\\label{tab:attack_precision_current}\n")
    tex.append("\\begin{tabular}{lcccccc}\n\\toprule\n")
    tex.append(" & \\multicolumn{3}{c}{\\textbf{Claude Haiku 4.5}}\n")
    tex.append(" & \\multicolumn{3}{c}{\\textbf{Gemini 2.5 Flash}} \\\\\n")
    tex.append("\\cmidrule(lr){2-4}\\cmidrule(lr){5-7}\n")
    tex.append("\\textbf{Dataset} & \\textbf{P} & \\textbf{R} & \\textbf{F1} & \\textbf{P} & \\textbf{R} & \\textbf{F1} \\\\\n\\midrule\n")
    for ds in DATASET_ORDER:
        try:
            h = grouped.loc[(ds, "anthropic")]; g = grouped.loc[(ds, "google")]
        except KeyError:
            continue
        tex.append(f"{DATASET_DISPLAY[ds]} & "
                   f"{h['attack_precision', 'mean']:.3f} & {h['attack_recall', 'mean']:.3f} & {h['attack_f1', 'mean']:.3f} & "
                   f"{g['attack_precision', 'mean']:.3f} & {g['attack_recall', 'mean']:.3f} & {g['attack_f1', 'mean']:.3f} \\\\\n")
    tex.append("\\bottomrule\n\\end{tabular}\n\\end{table}\n")

    (out_dir / "multi_seed_summary.tex").write_text("".join(tex))

    print(f"\nWritten:")
    for p in ["multi_seed_summary.csv", "multi_seed_summary.md", "multi_seed_summary.tex"]:
        print(f"  {out_dir/p}")


if __name__ == "__main__":
    main()
