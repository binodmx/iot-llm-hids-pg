"""Generate the paper-ready results table from the latest policy JSONs.

Compares Haiku vs Gemini macro F1 / attack F1 / attack precision / attack recall
across all 5 datasets, side-by-side with the canonical baseline numbers from
the paper. Outputs Markdown and LaTeX.

    python experiments/build_results_table.py
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

import numpy as np
import pandas as pd

REPO = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(REPO))

from lib.policy_pipeline.datasets import load_dataset
from lib.policy_pipeline.eval import classification_metrics
from lib.policy_pipeline.io import load_policy
from lib.policy_pipeline.voting import predict


# Canonical paper numbers (from results.tex `tab:policy_refinement` and `tab:attack_precision_current`)
CANONICAL = {
    "cic":   {"display": "CIC-IoT2023", "macro_f1_claim": 0.9426, "attack_f1_canonical": 0.9867,
              "note": "macro_f1 unreproducible; current reproducible = 0.8139"},
    "wustl": {"display": "WUSTL-IIoT",  "macro_f1_claim": 0.9252, "attack_f1_canonical": 0.9711},
    "ton":   {"display": "TON_IoT",     "macro_f1_claim": 0.7701, "attack_f1_canonical": 0.3671,
              "note": "macro_f1 unreproducible; current reproducible = 0.4865 (attack F1 is the canonical 0.3671)"},
    "bot":   {"display": "Bot-IoT",     "macro_f1_claim": 0.9232, "attack_f1_canonical": 0.9850},
    "unsw":  {"display": "UNSW-NB15",   "macro_f1_claim": 0.7507, "attack_f1_canonical": 0.7269},
}


def _latest(dataset_key: str, provider: str) -> Path | None:
    files = sorted((REPO / "experiments" / "policies" / dataset_key).glob(f"*-{provider}-*.json"))
    return files[-1] if files else None


def eval_policy(dataset_key: str, provider: str) -> dict | None:
    p = _latest(dataset_key, provider)
    if not p:
        return None
    doc, policy = load_policy(str(p))
    split = load_dataset(dataset_key, seed=doc["config"]["seed"])
    X_te = pd.concat([split.normal_test, split.attack_test], axis=0, ignore_index=True)
    y_te = np.concatenate([
        np.full(len(split.normal_test), "normal"),
        np.full(len(split.attack_test), "attack"),
    ])
    metrics = classification_metrics(y_te, predict(policy, X_te))
    return {
        "policy_file": p.name,
        "run_id": doc["run_id"],
        "best_round": doc["best_round"] + 1,
        "n_rules": len(policy.rules),
        "n_distinct_tags": len({r.phenomenon_tag for r in policy.rules}),
        "tags": sorted({r.phenomenon_tag for r in policy.rules}),
        "tokens_in": doc["tokens"]["input"],
        "tokens_out": doc["tokens"]["output"],
        "voting_mode": policy.voting_mode,
        "tau": policy.tau,
        **metrics,
    }


def main():
    rows = []
    for ds_key, meta in CANONICAL.items():
        row = {"dataset": meta["display"]}
        for prov in ["anthropic", "google"]:
            r = eval_policy(ds_key, prov)
            if r is None:
                row[f"{prov}_macro_f1"] = None
                continue
            short = "haiku" if prov == "anthropic" else "gemini"
            row[f"{short}_macro_f1"]   = r["macro_f1"]
            row[f"{short}_attack_f1"]  = r["attack_f1"]
            row[f"{short}_attack_p"]   = r["attack_precision"]
            row[f"{short}_attack_r"]   = r["attack_recall"]
            row[f"{short}_tags"]       = r["n_distinct_tags"]
            row[f"{short}_tokens"]     = f'{r["tokens_in"]}/{r["tokens_out"]}'
            row[f"{short}_round"]      = r["best_round"]
        row["paper_macro_claim"]       = meta["macro_f1_claim"]
        row["paper_attack_canonical"]  = meta["attack_f1_canonical"]
        rows.append(row)

    df = pd.DataFrame(rows)
    print("\n=== POLICY PIPELINE — Held-out Test Results ===\n")
    cols_compact = ["dataset", "haiku_macro_f1", "gemini_macro_f1",
                    "paper_macro_claim", "haiku_tags", "gemini_tags"]
    print(df[cols_compact].to_string(index=False, float_format=lambda x: f"{x:.4f}"))

    print("\n=== Per-class attack metrics ===\n")
    cols_attack = ["dataset",
                   "haiku_attack_f1", "haiku_attack_p", "haiku_attack_r",
                   "gemini_attack_f1", "gemini_attack_p", "gemini_attack_r"]
    print(df[cols_attack].to_string(index=False, float_format=lambda x: f"{x:.4f}"))

    # Write artefacts
    out_dir = REPO / "experiments" / "results"
    out_dir.mkdir(exist_ok=True)
    df.to_csv(out_dir / "pipeline_results.csv", index=False, float_format="%.4f")

    # Markdown
    md = ["# Policy Pipeline Results — Held-out Test\n"]
    md.append("Generated by `experiments/build_results_table.py` from the latest policy JSON per (dataset, provider).\n\n")
    md.append("## Macro F1 Summary\n\n")
    md.append("| Dataset | Haiku (new) | Gemini (new) | Paper claim (unreproducible) | Haiku tags | Gemini tags |\n")
    md.append("|---|---|---|---|---|---|\n")
    for _, r in df.iterrows():
        md.append(
            f"| {r['dataset']} | {r['haiku_macro_f1']:.4f} | {r['gemini_macro_f1']:.4f} | "
            f"{r['paper_macro_claim']:.4f} | {int(r['haiku_tags'])} | {int(r['gemini_tags'])} |\n"
        )
    md.append("\n## Attack-class metrics\n\n")
    md.append("| Dataset | Haiku attack F1 | Haiku P | Haiku R | Gemini attack F1 | Gemini P | Gemini R |\n")
    md.append("|---|---|---|---|---|---|---|\n")
    for _, r in df.iterrows():
        md.append(
            f"| {r['dataset']} | {r['haiku_attack_f1']:.4f} | {r['haiku_attack_p']:.4f} | "
            f"{r['haiku_attack_r']:.4f} | {r['gemini_attack_f1']:.4f} | {r['gemini_attack_p']:.4f} | "
            f"{r['gemini_attack_r']:.4f} |\n"
        )

    (out_dir / "pipeline_results.md").write_text("".join(md))

    # LaTeX
    tex = []
    tex.append("\\begin{table}[htbp]\n\\centering\n")
    tex.append("\\caption{Multi-model policy-pipeline results, balanced held-out test split, seed 42.\n")
    tex.append("  Each cell is best-round macro F1 / attack F1; phenomenon-tag count in parentheses.}\n")
    tex.append("\\label{tab:new_pipeline}\n")
    tex.append("\\begin{tabular}{lcccc}\n\\toprule\n")
    tex.append(" & \\multicolumn{2}{c}{Claude Haiku 4.5} & \\multicolumn{2}{c}{Gemini 2.5 Flash} \\\\\n")
    tex.append("\\cmidrule(lr){2-3}\\cmidrule(lr){4-5}\n")
    tex.append("\\textbf{Dataset} & \\textbf{Macro F1} & \\textbf{Attack F1} & \\textbf{Macro F1} & \\textbf{Attack F1} \\\\\n\\midrule\n")
    for _, r in df.iterrows():
        tex.append(
            f"{r['dataset']} & {r['haiku_macro_f1']:.4f} ({int(r['haiku_tags'])}) & {r['haiku_attack_f1']:.4f} & "
            f"{r['gemini_macro_f1']:.4f} ({int(r['gemini_tags'])}) & {r['gemini_attack_f1']:.4f} \\\\\n"
        )
    tex.append("\\bottomrule\n\\end{tabular}\n\\end{table}\n")
    (out_dir / "pipeline_results.tex").write_text("".join(tex))

    print(f"\nWritten:\n  {out_dir/'pipeline_results.csv'}\n  {out_dir/'pipeline_results.md'}\n  {out_dir/'pipeline_results.tex'}")


if __name__ == "__main__":
    main()
